/** Convierte un nombre en un slug de URL: minúsculas, sin acentos, guiones. Módulo puro (sin dependencias). */
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}
